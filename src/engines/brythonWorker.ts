// Worker thread that hosts the Brython runtime (Python transpiled to JS).
// Brython targets browsers, so a small browser environment is shimmed first:
// globals it probes at load time, and a synchronous XMLHttpRequest backed by
// the filesystem, which serves both Python module imports (sympy/mpmath from
// vendor/brython/lib) and unicode.txt (used for \N{...} escapes).
import * as fs from 'fs';
import * as path from 'path';
import { parentPort, workerData } from 'worker_threads';

interface WorkerRequest { id: number; language: string; expression: string; }

const { brythonDir, symplexPyPath } = workerData as {
	brythonDir: string; symplexPyPath: string;
};

// Brython resolves every URL against the page origin; map this fake origin
// onto the vendored directory on disk.
const ORIGIN = 'http://symplex.brython/';

const g = globalThis as Record<string, unknown>;
g.location = { href: ORIGIN + 'main.html', origin: ORIGIN.slice(0, -1), pathname: '/main.html' };
g.self = globalThis;
g.window = globalThis;
g.addEventListener = () => { };
g.removeEventListener = () => { };
g.dispatchEvent = () => true;
g.document = {
	getElementsByTagName: () => [{ src: ORIGIN + 'brython.js' }],
	currentScript: { src: ORIGIN + 'brython.js' },
	querySelectorAll: () => [],
	addEventListener: () => { },
	dispatchEvent: () => true
};
g.XMLHttpRequest = class {
	url = '';
	status = 404;
	readyState = 4;
	responseText = '';
	onreadystatechange: (() => void) | null = null;
	open(_method: string, url: string): void { this.url = String(url); }
	setRequestHeader(): void { }
	getResponseHeader(): null { return null; }
	overrideMimeType(): void { }
	abort(): void { }
	send(): void {
		const clean = this.url.split('?')[0];
		if (clean.startsWith(ORIGIN)) {
			const file = path.join(brythonDir, decodeURIComponent(clean.slice(ORIGIN.length)));
			// stay inside the vendored directory
			if (path.resolve(file).startsWith(path.resolve(brythonDir) + path.sep)) {
				try {
					this.responseText = fs.readFileSync(file, 'utf8');
					this.status = 200;
				} catch {
					this.status = 404;
				}
			}
		}
		this.onreadystatechange?.call(this);
	}
};

/* eslint-disable @typescript-eslint/no-require-imports, @typescript-eslint/no-explicit-any */
require(path.join(brythonDir, 'brython.js'));
const $B = (globalThis as any).__BRYTHON__;
// some code generated by Brython's parser expects $B as a global
(globalThis as any).$B = $B;
require(path.join(brythonDir, 'brython_stdlib.js'));
/* eslint-enable @typescript-eslint/no-require-imports */

function formatPythonError(error: unknown): string {
	const err = error as { args?: unknown[]; ob_type?: { tp_name?: string }; message?: string };
	const kind = err?.ob_type?.tp_name;
	const detail = Array.isArray(err?.args) && err.args.length ? String(err.args[0]) :
		(err?.message ?? String(error));
	return kind ? kind + ': ' + detail : detail;
}

let evaluateJson: ((language: string, expression: string) => string) | undefined;

function getEvaluator(): (language: string, expression: string) => string {
	if (!evaluateJson) {
		// sys.path must be set in the same script as the sympy import:
		// Brython caches the import path configuration per script
		$B.runPythonSource(
			'import sys\nsys.path.insert(0, "' + ORIGIN + 'lib")\n' +
			fs.readFileSync(symplexPyPath, 'utf8'), 'symplex_backend');
		const wrapper = $B.runPythonSource(
			'import json\n' +
			'import symplex_backend\n' +
			'def evaluate_json(language, expression):\n' +
			'    return json.dumps(symplex_backend.evaluate(language, expression))\n',
			'symplex_wrapper');
		evaluateJson = $B.$getattr(wrapper, 'evaluate_json');
	}
	return evaluateJson!;
}

if (!parentPort) { throw new Error('brythonWorker must be run as a worker thread.'); }

parentPort.on('message', (request: WorkerRequest) => {
	try {
		const resultJson = getEvaluator()(request.language, request.expression);
		parentPort!.postMessage({ id: request.id, result: JSON.parse(resultJson) });
	} catch (error) {
		parentPort!.postMessage({ id: request.id, error: formatPythonError(error) });
	}
});
